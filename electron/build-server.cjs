const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const output = path.join(root, '.desktop-build');
fs.mkdirSync(output, { recursive: true });
if (!fs.existsSync(path.join(root, 'web/dist/index.html'))) throw new Error('Build web/ with bun run build first.');
const name = process.platform === 'win32' ? 'hyxware.exe' : 'hyxware';
const result = spawnSync('go', ['build', '-o', path.join(output, name), '.'], { cwd: root, stdio: 'inherit', windowsHide: true });
process.exit(result.status ?? 1);
