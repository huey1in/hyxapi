func parseStatusFilter(statusParam string) int {
	switch strings.ToLower(statusParam) {
	case "enabled", "1":
		return common.ChannelStatusEnabled
	case "disabled", "0":
		return 0
	case "2":
		return common.ChannelStatusManuallyDisabled
	case "3":
		return common.ChannelStatusAutoDisabled
	default:
		return -1
	}
}

